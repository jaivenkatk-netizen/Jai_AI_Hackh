"""Does the twin residual beat the raw signal? Measured, not assumed.

The asset twin exists to supply a residual feature. The premise is that
`observed - healthy(conditions)` isolates degradation from the weather, so it
should correlate *more* with damage and *less* with ambient temperature than
the raw channel does. That premise is testable, and this script tests it
before anything is wired into the feature pipeline.

Run:

    python -m sim.twin_residual_check                # chillers, default sample
    python -m sim.twin_residual_check --asset-type rtu --n 1500

The result on this fleet is negative, and the mechanism is worth stating
because it is a property of the data rather than of the method:

  * The fleet's telemetry is generated by a linear signal model whose head
    pressure moves 26 kPa per K of ambient. Real saturation physics moves it
    about 60 kPa/K for R32 in this range, which is what the twin computes.
    The twin is the more physical of the two, but subtracting a 60 kPa/K
    model from a 26 kPa/K signal leaves a residual that tracks ambient at
    -34 kPa/K. Over-correction, so the residual carries more weather than
    the raw channel did, with the sign flipped.
  * Superheat and subcool are held at fixed setpoints by the twin, so their
    residual is the raw signal minus a constant. A tree ensemble is
    invariant to that, so those two cannot add information either.

Conclusion: the twin residual is not used as a model feature on this data.
Against real telemetry - where head pressure does follow saturation - the
same residual would remove a genuine confounder, which is why the twin is
kept and used for the what-if panel and the asset screen's healthy baseline.
The honest version of this differentiator is "the physics twin drives the
what-if", not "the physics twin improves the model".
"""

from __future__ import annotations

import argparse

import duckdb
import numpy as np
import pandas as pd

from sim.asset_twin import RESIDUAL_SIGNALS, residuals, spec_for_asset

QUERY = """
SELECT * FROM (
    SELECT t.ambient_t_max, t.load_frac,
           t.suction_p, t.discharge_p, t.superheat, t.subcool,
           GREATEST(1.0 - t.health_compressor,
                    1.0 - t.health_condenser_coil,
                    1.0 - t.health_refrigerant_circuit) AS dmg,
           a.asset_type, a.capacity_kw, a.refrigerant
    FROM telemetry_daily t JOIN assets a USING (asset_id)
    WHERE a.asset_type = ? AND t.suction_p IS NOT NULL
)
USING SAMPLE {n} ROWS (reservoir, 11)
"""
# The sample has to wrap the filtered subquery. Applied directly to the join
# it ran before the WHERE clause and returned 147 rows for a 900-row request,
# which would have made every correlation below far noisier than it looked.


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--db", default="data/servicesense.duckdb")
    ap.add_argument("--asset-type", default="chiller")
    ap.add_argument("--n", type=int, default=900, help="rows to sample")
    args = ap.parse_args()

    con = duckdb.connect(args.db, read_only=True)
    # DuckDB only accepts a literal in a SAMPLE clause, so the row
    # count is formatted in after being forced to an int.
    sql = QUERY.format(n=int(args.n))
    df = con.execute(sql, [args.asset_type]).df()
    if df.empty:
        raise SystemExit(f"no telemetry for asset_type={args.asset_type!r}")

    rows = []
    for r in df.itertuples(index=False):
        spec = spec_for_asset(r.asset_type, r.capacity_kw, r.refrigerant)
        observed = {s: getattr(r, s) for s in RESIDUAL_SIGNALS}
        try:
            res = residuals(observed, spec, r.ambient_t_max, r.load_frac)
        except Exception:
            continue  # a degraded machine can have no steady solution
        rows.append({"amb": r.ambient_t_max, "dmg": r.dmg, **res})

    R = pd.DataFrame(rows)
    if R.empty:
        raise SystemExit("no rows converged")

    def corr(a: pd.Series, b: pd.Series) -> float:
        return float(np.corrcoef(a, b)[0, 1])

    print(f"\nasset_type={args.asset_type}  n={len(R)} of {len(df)} sampled\n")
    print("A useful residual has |r(ambient)| SMALLER and |r(damage)| LARGER")
    print("than the raw channel it replaces.\n")
    header = f"{'signal':<16} {'r(ambient)':>11} {'r(damage)':>10}   {'verdict':<28}"
    print(header)
    print("-" * len(header))

    verdicts = []
    for sig in RESIDUAL_SIGNALS:
        key = f"{sig}_resid"
        raw_amb, raw_dmg = corr(df["ambient_t_max"], df[sig]), corr(df["dmg"], df[sig])
        res_amb, res_dmg = corr(R["amb"], R[key]), corr(R["dmg"], R[key])

        if abs(res_amb - raw_amb) < 1e-6 and abs(res_dmg - raw_dmg) < 1e-6:
            verdict = "no change (constant offset)"
        elif abs(res_amb) < abs(raw_amb) and abs(res_dmg) >= abs(raw_dmg):
            verdict = "BETTER"
        elif abs(res_amb) > abs(raw_amb):
            verdict = "WORSE (over-corrects ambient)"
        else:
            verdict = "WORSE (loses damage signal)"
        verdicts.append(verdict)

        print(f"{sig + ' raw':<16} {raw_amb:>+11.3f} {raw_dmg:>+10.3f}")
        print(f"{'  -> residual':<16} {res_amb:>+11.3f} {res_dmg:>+10.3f}   {verdict:<28}")

    improved = sum(v == "BETTER" for v in verdicts)
    print(f"\n{improved} of {len(RESIDUAL_SIGNALS)} signals improved.")
    if improved == 0:
        print(
            "VERDICT: do not use twin residuals as model features on this data.\n"
            "See this module's docstring for why - it is a property of the\n"
            "generator's linear signal model, not of the residual method."
        )


if __name__ == "__main__":
    main()
